export interface Call {
  file: string;
  args: string[];
}

/**
 * Fake slicer runner. Answers --help with `banner`, `flatpak list` with `flatpakList`, writes
 * G-code where PrusaSlicer (--output) or Orca/Bambu (--outputdir/plate_1.gcode, or the
 * --export-3mf file) would. `fail(args)` returning true makes that run exit 1 with no output.
 */
export function fakeExec(o: { gcode?: string; banner?: string; flatpakList?: string; fail?: (args: string[]) => boolean } = {}): { exec: ExecFileFn; calls: Call[] } {
  const calls: Call[] = [];
  const ok = (stdout = ""): ExecResult => ({ code: 0, stdout, stderr: "", timedOut: false });
  const exec: ExecFileFn = async (file, args) => {
    calls.push({ file, args });
    if (args[0] === "list") return ok(o.flatpakList ?? "");
    if (args.includes("--help")) return ok(o.banner ?? "PrusaSlicer-2.9.0+linux-x64-GTK3 based on Slic3r");
    if (o.fail?.(args)) return { code: 1, stdout: "", stderr: "Unknown printer profile", timedOut: false };
    const out = args.indexOf("--output");
    if (out >= 0) await writeFile(args[out + 1], o.gcode ?? PRUSA_GCODE);
    const dir = args.indexOf("--outputdir");
    if (dir >= 0) {
      const tmf = args.indexOf("--export-3mf");
      if (tmf >= 0) await writeFile(join(args[dir + 1], args[tmf + 1]), zipStored({ "[Content_Types].xml": "<Types/>", "Metadata/plate_1.gcode": o.gcode ?? BAMBU_GCODE }));
      else await writeFile(join(args[dir + 1], "plate_1.gcode"), o.gcode ?? ORCA_GCODE);
    }
    return ok("Slicing done");
  };
  return { exec, calls };
}
