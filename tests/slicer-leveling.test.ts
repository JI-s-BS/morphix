// Bed leveling before every print, and print speeds left to the profiles. Never touches a
// printer: the slicer is a fake runner and everything stays in temp files.
import { mkdtemp, readFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { describe, expect, it } from "vitest";
import * as slicing from "@morphix/slicing";
import { capFirstLayers,
  applyLeveling,
  LEVEL_MARKER,
  levelingPlan,
  parsePrusaIni,
  preparePrint,
  readGx,
  resolveProfilePaths,
  startSequence,
  validateGx,
  validateLevelCommands,
  writeBinaryStl,
  type SlicerInfo,
} from "@morphix/slicing";
import { box, fakeSlicerExec, PRUSA_GCODE } from "./phase3-fixtures";

const PROFILES = resolve(__dirname, "..", "config", "slicer-profiles");
const PRUSA: SlicerInfo = { kind: "prusaslicer", path: "/usr/bin/prusa-slicer", version: "2.9.0" };
const tmp = () => mkdtemp(join(tmpdir(), "morphix-level-"));

/** The profile's start G-code as PrusaSlicer would write it (placeholders filled in). */
async function prusaStart(): Promise<string> {
  const ini = parsePrusaIni(await readFile(resolveProfilePaths(PROFILES)!.prusaIni, "utf8"));
  return ini.start_gcode.replace(/\\n/g, "\n").replace(/\[first_layer_bed_temperature\]/g, "60").replace(/\[first_layer_temperature\]/g, "210");
}

/** Sliced G-code = profile start G-code + the fixture's layers. */
async function slicedWithProfileStart(): Promise<string> {
  const layers = PRUSA_GCODE.slice(PRUSA_GCODE.indexOf(";LAYER_CHANGE"));
  return `; generated by PrusaSlicer 2.9.0+linux-aarch64 on 2026-11-08 at 10:00:00 UTC\n${await prusaStart()}\n${layers}`;
}

describe("purge line", () => {
  it("is 2 x 200 mm along the front edge at 150% flow, in both slicer profiles", async () => {
    const { readFileSync } = await import("node:fs");
    const ini = readFileSync(resolve(PROFILES, "qd330-pla-0.2mm.ini"), "utf8");
    const orca = JSON.parse(readFileSync(resolve(PROFILES, "orcaslicer/qd330-machine.json"), "utf8")).machine_start_gcode as string;
    for (const start of [ini.match(/^start_gcode = (.*)$/m)![1].replace(/\\n/g, "\n"), orca]) {
      expect(start).toContain("G1 X100 Y-100 E30 F600"); // 200 mm, 30 mm filament = 0.15/mm (was 0.10/mm)
      expect(start).toContain("G1 X-100 Y-99.2 E60 F600"); // and 200 mm back
    }
  });
});

describe("start G-code: home, bed at temperature, level, heat nozzle, prime", () => {
  it("PrusaSlicer profile has the leveling step in the right place", async () => {
    const s = startSequence(await prusaStart());
    expect(s.home).toBeGreaterThanOrEqual(0);
    expect(s.level).toBeGreaterThan(s.home);
    expect(s.bedWait).toBeLessThan(s.level);
    expect(s.nozzleWait).toBeGreaterThan(s.level);
    expect(s.prime).toBeGreaterThan(s.nozzleWait);
    expect(s.ordered).toBe(true);
  });

  it("OrcaSlicer fallback profile has the same order and a centre-origin bed", async () => {
    const machine = JSON.parse(await readFile(resolveProfilePaths(PROFILES)!.orcaMachine, "utf8"));
    expect(startSequence(machine.machine_start_gcode).ordered).toBe(true);
    // The QD330 bed runs -110..110 (G28 parks at X/Y 110); 0..220 put models half off the bed.
    expect(machine.printable_area).toEqual(["-110x-110", "110x-110", "110x110", "-110x110"]);
  });
});

describe("applyLeveling", () => {
  it("printer mode (MORPHIX_LEVELING=printer): adds no command, leaves a comment where leveling happens", async () => {
    const g = await slicedWithProfileStart();
    const { gcode, report } = applyLeveling(g, { mode: "printer" });
    expect(report).toMatchObject({ mode: "printer", commands: [], markerFound: true });
    expect(gcode).not.toContain(LEVEL_MARKER);
    expect(gcode).not.toMatch(/^G29\b/m);
    expect(gcode).toMatch(/QD330 levels the bed itself/);
    expect(gcode.split("\n").length).toBe(g.split("\n").length);
  });

  it("gcode mode (default): writes the command after homing, before the nozzle heats", async () => {
    const plan = levelingPlan();
    expect(plan).toEqual({ mode: "gcode", commands: ["G29"], verified: false });
    const { gcode, report } = applyLeveling(await slicedWithProfileStart(), plan);
    expect(report).toMatchObject({ mode: "gcode", commands: ["G29"], markerFound: true, warnings: [] });
    const s = startSequence(gcode);
    expect(s.ordered).toBe(true);
    const lines = gcode.split("\n");
    expect(lines[s.level + 1]).toBe("G29");
    expect(lines[s.level + 2]).toMatch(/^G1 Z10 F600\b/); // lifted before travelling to the prime line
  });

  it("without the marker, gcode mode levels straight after G28 and says so", () => {
    const { gcode, report } = applyLeveling(PRUSA_GCODE, levelingPlan());
    const lines = gcode.split("\n");
    expect(lines[lines.indexOf("G28") + 2]).toBe("G29");
    expect(report.markerFound).toBe(false);
    expect(report.warnings.join(" ")).toMatch(/no ;MORPHIX_LEVEL_BED/);
  });

  it("printer mode leaves G-code without the marker untouched", () => {
    expect(applyLeveling(PRUSA_GCODE, { mode: "printer" }).gcode).toBe(PRUSA_GCODE);
  });

  it("levels by default when no plan is given", async () => {
    expect(applyLeveling(await slicedWithProfileStart()).report).toMatchObject({ mode: "gcode", commands: ["G29"] });
  });
});

describe("levelingPlan / validateLevelCommands", () => {
  it("levels in every print with G29 unless MORPHIX_LEVELING=printer", () => {
    expect(levelingPlan()).toEqual({ mode: "gcode", commands: ["G29"], verified: false });
    expect(levelingPlan({ printerOnly: true, commandsText: "G29" })).toEqual({ mode: "printer" });
  });

  it("takes MORPHIX_LEVEL_GCODE in place of G29", () => {
    expect(levelingPlan({ commandsText: "BED_MESH_CALIBRATE PROFILE=default; G29 P1" })).toEqual({
      mode: "gcode", commands: ["BED_MESH_CALIBRATE PROFILE=default", "G29 P1"], verified: false,
    });
  });

  it("refuses commands that move, heat, extrude, control jobs or change the firmware", () => {
    for (const bad of ["G1 Z0", "G28", "M104 S250", "M140 S100", "M109 S200", "M112", "M23 0:/user/x.gx", "M26", "M601 S1", "SAVE_CONFIG", "FIRMWARE_RESTART", "M500", "G92 E0"]) {
      expect(() => validateLevelCommands([bad]), bad).toThrow();
    }
    for (const bad of ["G29\nG1 Z0", "g29", "G29 ; x", "", "G29 X=1;M112"]) expect(() => validateLevelCommands([bad]), JSON.stringify(bad)).toThrow();
    expect(() => validateLevelCommands([])).toThrow();
    expect(() => levelingPlan({ commandsText: "G29; M112" })).toThrow(/M112/);
  });
});

describe("preparePrint", () => {
  it("writes leveling into the .gx in order, and leaves the profile's speeds alone", async () => {
    const sliced = await slicedWithProfileStart();
    const { exec } = fakeSlicerExec(sliced);
    const r = await preparePrint({
      buffer: writeBinaryStl(box(20, 20, 20, { x: 0, y: 0, z: 0 })),
      format: "stl",
      options: { outputDir: await tmp(), slicer: PRUSA, profilesDir: PROFILES, exec, upAxis: "z", leveling: levelingPlan() },
    });
    if (!r.gx.ok) throw new Error(r.gx.message);
    expect(validateGx(r.gx.buffer).ok).toBe(true);
    const gcode = readGx(r.gx.buffer).gcode.toString();
    expect(startSequence(gcode).ordered).toBe(true);
    expect(gcode).toMatch(/^G29$/m);
    expect(r.leveling).toMatchObject({ mode: "gcode", markerFound: true });
    expect(r.warnings.join(" ")).toMatch(/UNVERIFIED command \(G29\)/);
    // Only the first-layer caps change feed rates (layer 1: 20, layer 2: 30, travel 100 mm/s).
    const feeds = (t: string) => t.slice(t.indexOf(";LAYER_CHANGE")).match(/\bF\d+/g);
    expect(feeds(gcode)).toEqual(feeds(capFirstLayers(sliced)));
    expect(gcode).not.toMatch(/layers at \d+% speed/);
    expect(await readFile(r.files.gcode!, "utf8")).toBe(gcode);
  });

  it("levels the bed in every print by default", async () => {
    const { exec } = fakeSlicerExec(await slicedWithProfileStart());
    const r = await preparePrint({ buffer: writeBinaryStl(box(20, 20, 20, { x: 0, y: 0, z: 0 })), format: "stl", options: { outputDir: await tmp(), slicer: PRUSA, profilesDir: PROFILES, exec, upAxis: "z" } });
    if (!r.gx.ok) throw new Error(r.gx.message);
    expect(r.leveling).toMatchObject({ mode: "gcode", commands: ["G29"], markerFound: true });
    const gcode = readGx(r.gx.buffer).gcode.toString();
    expect(gcode).toMatch(/^G29$/m);
    expect(startSequence(gcode).ordered).toBe(true);
  });

  it("MORPHIX_LEVELING=printer leaves it to the printer", async () => {
    const { exec } = fakeSlicerExec(await slicedWithProfileStart());
    const r = await preparePrint({ buffer: writeBinaryStl(box(20, 20, 20, { x: 0, y: 0, z: 0 })), format: "stl", options: { outputDir: await tmp(), slicer: PRUSA, profilesDir: PROFILES, exec, upAxis: "z", leveling: levelingPlan({ printerOnly: true }) } });
    if (!r.gx.ok) throw new Error(r.gx.message);
    expect(r.leveling).toMatchObject({ mode: "printer", commands: [] });
    expect(readGx(r.gx.buffer).gcode.toString()).not.toMatch(/^G29$/m);
  });

  it("the first-layer slowdown is gone from the library", () => {
    expect("slowFirstLayers" in slicing).toBe(false);
  });
});
