// G-code analysis: slicer-reported estimates (PrusaSlicer / OrcaSlicer comment formats),
// a fallback estimate computed from the moves themselves, and per-layer toolpaths for a
// layer-preview UI.

export interface GcodeEstimates {
  /** Seconds; slicer value when available, otherwise a crude feedrate-based estimate. */
  printTimeS: number | null;
  filamentMm: number | null;
  filamentG: number | null;
  filamentCm3: number | null;
  layerCount: number;
  layerHeightMm: number | null;
  /** Max Z reached while extruding. */
  maxZMm: number;
  nozzleTempC: number | null;
  bedTempC: number | null;
  /** Generator detected from header comments ("PrusaSlicer 2.9.0", "OrcaSlicer 2.2.0", ...). */
  generator: string | null;
  /** Where each estimate came from. */
  source: { time: "slicer" | "computed" | null; filament: "slicer" | "computed" | null };
}

export interface FilamentSpec {
  diameterMm: number;
  densityGcm3: number;
}

export const PLA_175: FilamentSpec = { diameterMm: 1.75, densityGcm3: 1.24 };

/** Parses "1d 2h 3m 4s" / "2h 3m" / "45s" into seconds. */
export function parseDuration(s: string): number | null {
  let total = 0, matched = false;
  for (const m of s.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])/g)) {
    matched = true;
    total += Number(m[1]) * { d: 86400, h: 3600, m: 60, s: 1 }[m[2] as "d" | "h" | "m" | "s"];
  }
  return matched ? Math.round(total) : null;
}

const sumList = (s: string) => s.split(/[,;]/).map((x) => Number(x.trim())).filter((x) => Number.isFinite(x)).reduce((a, b) => a + b, 0);

/** Reads slicer-reported values from comments, then fills gaps by simulating the moves. */
export function analyzeGcode(text: string, filament: FilamentSpec = PLA_175): GcodeEstimates {
  let time: number | null = null, mm: number | null = null, g: number | null = null, cm3: number | null = null;
  let layers: number | null = null, layerH: number | null = null, generator: string | null = null;
  let nozzle: number | null = null, bed: number | null = null;
  let firstLines = 0;
  for (const raw of iterateLines(text)) {
    const line = raw.trim();
    if (firstLines < 20) {
      firstLines++;
      const gm = /generated by\s+([A-Za-z][\w.-]*(?:\s+[\d][\w.+-]*)?)/i.exec(line);
      if (gm && !generator) generator = gm[1];
    }
    if (line[0] !== ";") {
      // First temperature commands give the job temperatures.
      if (nozzle === null) {
        const m = /^M10[49]\b.*\bS(\d+(?:\.\d+)?)/.exec(line);
        if (m && Number(m[1]) > 0) nozzle = Number(m[1]);
      }
      if (bed === null) {
        const m = /^M1(?:40|90)\b.*\bS(\d+(?:\.\d+)?)/.exec(line);
        if (m && Number(m[1]) > 0) bed = Number(m[1]);
      }
      continue;
    }
    let m: RegExpExecArray | null;
    if ((m = /^;\s*estimated printing time(?: \(normal mode\))?\s*[=:]\s*(.+)$/i.exec(line)) && time === null) time = parseDuration(m[1]);
    else if ((m = /total estimated time:\s*([^;]+)/i.exec(line)) && time === null) time = parseDuration(m[1]);
    else if ((m = /^;\s*TIME:\s*(\d+)/.exec(line)) && time === null) time = Number(m[1]); // Cura
    else if ((m = /^;\s*(?:total )?filament used \[mm\]\s*[=:]\s*(.+)$/i.exec(line)) && mm === null) mm = sumList(m[1]);
    else if ((m = /^;\s*(?:total )?filament used \[g\]\s*[=:]\s*(.+)$/i.exec(line)) && g === null) g = sumList(m[1]);
    else if ((m = /^;\s*(?:total )?filament used \[cm3\]\s*[=:]\s*(.+)$/i.exec(line)) && cm3 === null) cm3 = sumList(m[1]);
    else if ((m = /^;\s*total layers? (?:number|count):\s*(\d+)/i.exec(line))) layers = Number(m[1]);
    else if ((m = /^;\s*LAYER_COUNT:\s*(\d+)/i.exec(line))) layers = Number(m[1]); // Cura
    else if ((m = /^;\s*layer_height\s*=\s*([\d.]+)/i.exec(line)) && layerH === null) layerH = Number(m[1]);
    else if ((m = /^;\s*Layer height:\s*([\d.]+)/i.exec(line)) && layerH === null) layerH = Number(m[1]);
  }
  const sim = simulate(text);
  const area = Math.PI * (filament.diameterMm / 2) ** 2;
  const filamentMm = mm ?? (sim.extrudedMm > 0 ? sim.extrudedMm : null);
  if (cm3 === null && filamentMm !== null) cm3 = (filamentMm * area) / 1000;
  if (g === null && cm3 !== null) g = cm3 * filament.densityGcm3;
  return {
    printTimeS: time ?? (sim.timeS > 0 ? Math.round(sim.timeS) : null),
    filamentMm,
    filamentG: g,
    filamentCm3: cm3,
    layerCount: layers ?? sim.layerZs.length,
    layerHeightMm: layerH ?? sim.typicalLayerHeight,
    maxZMm: sim.layerZs.length ? sim.layerZs[sim.layerZs.length - 1] : 0,
    nozzleTempC: nozzle,
    bedTempC: bed,
    generator,
    source: { time: time !== null ? "slicer" : sim.timeS > 0 ? "computed" : null, filament: mm !== null ? "slicer" : filamentMm !== null ? "computed" : null },
  };
}

// ------------------------------------------------------------------ toolpaths

export type PathKind = "extrude" | "travel";

export interface ToolpathSegmentGroup {
  kind: PathKind;
  /** Slicer feature label (";TYPE:" / "; FEATURE:"), e.g. "External perimeter", if known. */
  feature: string | null;
  /** Flat [x0, y0, x1, y1, ...] polyline in mm. */
  points: number[];
}

export interface Layer {
  index: number;
  z: number;
  heightMm: number;
  paths: ToolpathSegmentGroup[];
  extrudedMm: number;
}

export interface LayerExtractOptions {
  includeTravel?: boolean;
  /** Stop after this many layers (memory guard for the kiosk). */
  maxLayers?: number;
}

/**
 * Splits G-code into layers. A new layer starts at the first extruding move at a new Z,
 * which works for any slicer (no reliance on layer-change comments). Arcs (G2/G3) are
 * approximated by their chord.
 */
export function extractLayers(text: string, opts: LayerExtractOptions = {}): Layer[] {
  const layers: Layer[] = [];
  const includeTravel = opts.includeTravel ?? false;
  const max = opts.maxLayers ?? Infinity;
  let cur: Layer | null = null;
  let group: ToolpathSegmentGroup | null = null;
  let feature: string | null = null;
  const st = newState();
  for (const raw of iterateLines(text)) {
    const fm = /^;\s*(?:TYPE|FEATURE):\s*(.+)$/.exec(raw.trim());
    if (fm) {
      feature = fm[1].trim();
      group = null;
      continue;
    }
    const mv = step(st, raw);
    if (!mv) continue;
    const extruding = mv.de > 1e-9 && (mv.dx !== 0 || mv.dy !== 0);
    if (extruding && (!cur || Math.abs(st.z - cur.z) > 1e-4)) {
      if (layers.length >= max) break;
      const prevZ: number = cur ? cur.z : 0;
      cur = { index: layers.length, z: round4(st.z), heightMm: round4(st.z - prevZ), paths: [], extrudedMm: 0 };
      layers.push(cur);
      group = null;
    }
    if (!cur) continue;
    const kind: PathKind = extruding ? "extrude" : "travel";
    if (kind === "travel" && !includeTravel) {
      group = null;
      continue;
    }
    if (mv.dx === 0 && mv.dy === 0) continue;
    if (!group || group.kind !== kind || group.feature !== feature) {
      group = { kind, feature, points: [round4(st.x - mv.dx), round4(st.y - mv.dy)] };
      cur.paths.push(group);
    }
    group.points.push(round4(st.x), round4(st.y));
    if (extruding) cur.extrudedMm += mv.de;
  }
  return layers;
}

// ------------------------------------------------------------------ simulator

interface State {
  x: number; y: number; z: number; e: number; f: number;
  absXYZ: boolean; absE: boolean; inches: boolean;
}

const newState = (): State => ({ x: 0, y: 0, z: 0, e: 0, f: 1800, absXYZ: true, absE: true, inches: false });
const round4 = (v: number) => Math.round(v * 1e4) / 1e4;

/** Applies one line; returns the move deltas for G0-G3, null otherwise. */
function step(st: State, raw: string): { dx: number; dy: number; dz: number; de: number } | null {
  const semi = raw.indexOf(";");
  const line = (semi >= 0 ? raw.slice(0, semi) : raw).trim().toUpperCase();
  if (!line) return null;
  const words = line.split(/\s+/);
  const cmd = words[0];
  const val = (letter: string): number | undefined => {
    for (let i = 1; i < words.length; i++) if (words[i][0] === letter) return Number(words[i].slice(1));
    return undefined;
  };
  switch (cmd) {
    case "G90": st.absXYZ = true; st.absE = true; return null; // Marlin: G90 also sets E absolute
    case "G91": st.absXYZ = false; st.absE = false; return null;
    case "M82": st.absE = true; return null;
    case "M83": st.absE = false; return null;
    case "G20": st.inches = true; return null;
    case "G21": st.inches = false; return null;
    case "G92": {
      const e = val("E"); if (e !== undefined) st.e = e;
      const x = val("X"); if (x !== undefined) st.x = x;
      const y = val("Y"); if (y !== undefined) st.y = y;
      const z = val("Z"); if (z !== undefined) st.z = z;
      return null;
    }
    case "G28": st.x = 0; st.y = 0; st.z = 0; return null;
    case "G0": case "G1": case "G2": case "G3": case "G00": case "G01": case "G02": case "G03": {
      const k = st.inches ? 25.4 : 1;
      const nx = val("X"), ny = val("Y"), nz = val("Z"), ne = val("E"), nf = val("F");
      if (nf !== undefined && nf > 0) st.f = nf * k;
      const tx = nx === undefined ? st.x : st.absXYZ ? nx * k : st.x + nx * k;
      const ty = ny === undefined ? st.y : st.absXYZ ? ny * k : st.y + ny * k;
      const tz = nz === undefined ? st.z : st.absXYZ ? nz * k : st.z + nz * k;
      const te = ne === undefined ? st.e : st.absE ? ne * k : st.e + ne * k;
      const d = { dx: tx - st.x, dy: ty - st.y, dz: tz - st.z, de: te - st.e };
      st.x = tx; st.y = ty; st.z = tz; st.e = te;
      return d;
    }
    default:
      return null;
  }
}

function simulate(text: string): { timeS: number; extrudedMm: number; layerZs: number[]; typicalLayerHeight: number | null } {
  const st = newState();
  let time = 0, extruded = 0;
  const zs: number[] = [];
  for (const raw of iterateLines(text)) {
    const mv = step(st, raw);
    if (mv) {
      const dist = Math.hypot(mv.dx, mv.dy, mv.dz) || Math.abs(mv.de);
      if (st.f > 0) time += dist / (st.f / 60);
      if (mv.de > 0) extruded += mv.de;
      if (mv.de > 1e-9 && (mv.dx !== 0 || mv.dy !== 0) && (zs.length === 0 || Math.abs(zs[zs.length - 1] - st.z) > 1e-4)) zs.push(round4(st.z));
      continue;
    }
    const dwell = /^\s*G4\b.*?\b([PS])(\d+(?:\.\d+)?)/i.exec(raw.split(";")[0]);
    if (dwell) time += dwell[1].toUpperCase() === "P" ? Number(dwell[2]) / 1000 : Number(dwell[2]);
  }
  // Pure feedrate time ignores acceleration; real prints take noticeably longer.
  const heights = zs.map((z, i) => round4(i ? z - zs[i - 1] : z)).filter((h) => h > 0);
  const typical = heights.length ? mode(heights.slice(1).length ? heights.slice(1) : heights) : null;
  return { timeS: time * 1.15, extrudedMm: extruded, layerZs: zs, typicalLayerHeight: typical };
}

function mode(xs: number[]): number {
  const counts = new Map<number, number>();
  for (const x of xs) counts.set(x, (counts.get(x) ?? 0) + 1);
  return [...counts.entries()].sort((a, b) => b[1] - a[1])[0][0];
}

function* iterateLines(text: string): Iterable<string> {
  let start = 0;
  while (start <= text.length) {
    let end = text.indexOf("\n", start);
    if (end < 0) end = text.length;
    yield text.charCodeAt(end - 1) === 13 ? text.slice(start, end - 1) : text.slice(start, end);
    start = end + 1;
  }
}

/** Print-speed cap per starting layer (layer 1, layer 2…), whatever speed was chosen, mm/s. */
export const FIRST_LAYER_CAPS_MMS = [20, 30];
/** Travel-speed cap (X/Y moves without extrusion) during those layers, mm/s. */
export const FIRST_LAYERS_TRAVEL_MAX_MMS = 100;

/**
 * Slows the first layers whatever speed was sliced: printing moves (G1/G2/G3 with X/Y and E)
 * in layer N are capped at caps[N] (20 mm/s for layer 1, 30 for layer 2), and X/Y travel moves
 * in those layers at `travelMaxMmS`. Retractions and Z moves keep their speed, and the sliced
 * feed rate comes back from the next layer on. Layers are counted by the ";LAYER_CHANGE" marker
 * PrusaSlicer and OrcaSlicer write (start G-code before it is left alone). F is modal, so the
 * feed rate actually in force is tracked and rewritten as needed.
 */
export function capFirstLayers(gcode: string, caps: number[] = FIRST_LAYER_CAPS_MMS, travelMaxMmS = FIRST_LAYERS_TRAVEL_MAX_MMS): string {
  if (!caps.length || !gcode.includes(";LAYER_CHANGE")) return gcode;
  const out: string[] = [];
  let layer = -1;
  let slicedF: number | null = null; // feed rate the slicer meant
  let actualF: number | null = null; // feed rate in force after our edits
  let heldFan: string | null = null; // part-fan command held back until the slow layers are done
  for (const line of gcode.split("\n")) {
    if (/^;LAYER_CHANGE\b/.test(line)) {
      layer++;
      out.push(line);
      if (layer === 0) {
        out.push(`; Morphix: layer speeds ${caps.map((c, i) => `${i + 1}: ${c} mm/s`).join(", ")}; travel at most ${travelMaxMmS} mm/s`);
        out.push(`M107 ; Morphix: part fan off for the first ${caps.length} layers`);
      }
      if (layer === caps.length && heldFan) out.push(`${heldFan} ; Morphix: part fan on after the slow layers`);
      continue;
    }
    // The part fan stays off in the slow layers whatever the slicer asked for.
    if (layer >= 0 && layer < caps.length && /^M10[67](?:\s|;|$)/.test(line)) {
      const code = line.split(";")[0].trim();
      if (code.startsWith("M107") || /\bS0*(?:\.0*)?$/.test(code)) {
        heldFan = null;
        out.push(line);
      } else {
        heldFan = code;
        out.push(`; Morphix: held until layer ${caps.length + 1}: ${code}`);
      }
      continue;
    }
    if (!/^G[0-3](?:\s|$)/.test(line)) {
      out.push(line);
      continue;
    }
    const f = /\sF(\d*\.?\d+)/.exec(line);
    if (f) slicedF = Number(f[1]);
    const xy = /\s[XY]-?\d/.test(line);
    const printing = xy && /\sE-?\d/.test(line);
    const travel = xy && !printing;
    const inCapped = layer >= 0 && layer < caps.length;
    const cap = inCapped ? (printing ? caps[layer] : travel ? travelMaxMmS : null) : null;
    const want = slicedF === null ? null : cap !== null && cap > 0 ? Math.min(slicedF, cap * 60) : slicedF;
    if (want === null || want === actualF) {
      out.push(line);
      if (f) actualF = Number(f[1]);
      continue;
    }
    const code = line.split(";")[0].trimEnd();
    const comment = line.slice(code.length);
    out.push((f ? code.replace(/\sF\d*\.?\d+/, ` F${Math.round(want)}`) : `${code} F${Math.round(want)}`) + comment);
    actualF = want;
  }
  return out.join("\n");
}
